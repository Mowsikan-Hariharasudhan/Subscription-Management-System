import React, { useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { useNavigate } from 'react-router-dom';
import { Search, Receipt, Filter, Zap } from 'lucide-react';
import { invoiceService } from '../../services/invoiceService';
import { Invoice, InvoiceStatus } from '../../types';
import { PageHeader } from '../../components/shared/PageHeader';
import { DataTable, Column } from '../../components/shared/DataTable';
import { Pagination } from '../../components/shared/Pagination';
import { StatusBadge } from '../../components/shared/StatusBadge';
import { CurrencyDisplay } from '../../components/shared/CurrencyDisplay';
import { Button } from '../../components/ui/button';
import { Input } from '../../components/ui/input';
import { useAuth } from '../../context/AuthContext';
import { formatDate } from '../../lib/utils';

const STATUS_OPTIONS: InvoiceStatus[] = ['DRAFT', 'CONFIRMED', 'PAID', 'CANCELLED'];

export const Invoices: React.FC = () => {
  const [page, setPage] = useState(1);
  const [search, setSearch] = useState('');
  const [statusFilter, setStatusFilter] = useState('');
  const navigate = useNavigate();
  const { role } = useAuth();
  const queryClient = useQueryClient();

  const { data, isLoading } = useQuery({
    queryKey: ['invoices', { page, search, status: statusFilter }],
    queryFn: () => invoiceService.list({ page, limit: 10, search, status: statusFilter || undefined }),
  });

  const billingMutation = useMutation({
    mutationFn: () => invoiceService.runBillingNow(),
    onSuccess: (res) => {
      queryClient.invalidateQueries({ queryKey: ['invoices'] });
      alert(`Billing complete. Created: ${res.data?.created ?? 0} invoices, Skipped: ${res.data?.skipped ?? 0}`);
    },
    onError: (err: any) => {
      alert(`Billing failed: ${err.response?.data?.message || err.message}`);
    },
  });

  const columns: Column<Invoice>[] = [
    {
      header: 'Invoice #',
      cell: (inv) => (
        <span className="font-mono text-xs font-semibold text-plum-primary">{inv.number}</span>
      ),
    },
    {
      header: 'Customer',
      cell: (inv) => (
        <div>
          <p className="font-medium text-xs text-text-primary">{inv.customer?.name}</p>
          <p className="text-[11px] text-text-secondary font-mono">{inv.subscription?.number}</p>
        </div>
      ),
    },
    {
      header: 'Period',
      cell: (inv) => (
        <span className="text-xs text-text-secondary font-mono">
          {formatDate(inv.periodStart)} – {formatDate(inv.periodEnd)}
        </span>
      ),
    },
    {
      header: 'Status',
      cell: (inv) => <StatusBadge status={inv.status} />,
    },
    {
      header: 'Total',
      cell: (inv) => <CurrencyDisplay amount={inv.total} size="sm" className="font-semibold font-mono" />,
    },
    {
      header: 'Outstanding',
      cell: (inv) => (
        <CurrencyDisplay
          amount={inv.outstanding}
          size="sm"
          className={`font-mono ${inv.outstanding > 0 && inv.status === 'CONFIRMED' ? 'text-rose-600 font-semibold' : ''}`}
        />
      ),
    },
    {
      header: 'Due Date',
      cell: (inv) => {
        const isOverdue = inv.status === 'CONFIRMED' && inv.outstanding > 0 && new Date(inv.dueDate) < new Date();
        return (
          <span className={`text-xs font-mono ${isOverdue ? 'text-rose-600 font-semibold' : 'text-text-secondary'}`}>
            {formatDate(inv.dueDate)}
            {isOverdue && ' ⚠️'}
          </span>
        );
      },
    },
  ];

  return (
    <div className="space-y-4">
      <PageHeader
        title="Invoices"
        description="Recurring billing invoices generated by active subscriptions"
        actions={
          role === 'ADMIN' ? (
            <Button
              size="sm"
              variant="outline"
              onClick={() => billingMutation.mutate()}
              isLoading={billingMutation.isPending}
            >
              <Zap className="w-3.5 h-3.5 mr-1.5 text-amber-500" /> Run Billing Now
            </Button>
          ) : undefined
        }
      />

      <div className="bg-white p-3 rounded-lg border border-border-main shadow-subtle flex flex-wrap items-center gap-3">
        <div className="relative flex-1 min-w-[200px] max-w-xs">
          <Input
            placeholder="Search by invoice # or customer..."
            value={search}
            onChange={(e) => { setSearch(e.target.value); setPage(1); }}
            className="pl-9 h-9 text-xs"
          />
          <Search className="w-4 h-4 text-text-secondary absolute left-3 top-2.5" />
        </div>
        <div className="flex items-center space-x-2">
          <Filter className="w-4 h-4 text-text-secondary" />
          <select
            value={statusFilter}
            onChange={(e) => { setStatusFilter(e.target.value); setPage(1); }}
            className="h-9 rounded-md border border-border-main bg-white px-3 text-xs text-text-primary focus:outline-none focus:border-plum-primary focus:ring-1 focus:ring-plum-primary"
          >
            <option value="">All Statuses</option>
            {STATUS_OPTIONS.map((s) => (
              <option key={s} value={s}>{s}</option>
            ))}
          </select>
        </div>
        <div className="ml-auto flex items-center space-x-1.5 text-xs text-text-secondary font-mono">
          <Receipt className="w-4 h-4" />
          <span>{data?.pagination?.total ?? 0} total invoices</span>
        </div>
      </div>

      <DataTable
        columns={columns}
        data={data?.data || []}
        isLoading={isLoading}
        onRowClick={(inv) => navigate(`/invoices/${inv.id}`)}
        emptyTitle="No invoices found"
        emptyDescription="Invoices are generated automatically by the billing engine."
      />

      {data?.pagination && (
        <Pagination
          page={page}
          totalPages={data.pagination.totalPages}
          total={data.pagination.total}
          limit={data.pagination.limit}
          onPageChange={setPage}
        />
      )}
    </div>
  );
};
